def main():
    with open(EXERCISES_FILE, "r", encoding="utf-8") as f:
        exercises = json.load(f)

    updated_opts = 0
    for e in exercises:
        eid = e.get("id")
        if eid in FINAL_REPAIRS:
            patch = FINAL_REPAIRS[eid]
            expl = e.get("explanation", {})
            if isinstance(expl, dict):
                options = expl.get("options", [])
                for opt in options:
                    otxt = opt.get("text", "").strip()
                    if otxt in patch:
                        is_corr = opt.get("isCorrect", False)
                        prefix = "【正解】" if is_corr else "【不正解】"
                        opt["reason"] = f"{prefix}{patch[otxt]}"
                        updated_opts += 1

    with open(EXERCISES_FILE, "w", encoding="utf-8") as f:
        json.dump(exercises, f, ensure_ascii=False, indent=2)

    print(f"Successfully repaired {updated_opts} remaining options across 49 exercises.")

if __name__ == "__main__":
    main()
